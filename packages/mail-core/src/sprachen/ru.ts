/**
 * Russisch.
 *
 * Der Schluessel ist der deutsche Text - so steht er auch im Quelltext, und ein fehlender
 * Eintrag faellt auf Englisch und dann auf Deutsch zurueck, nie auf einen Bezeichner.
 * Was hier fehlt, findet `npm run sprachstand`.
 *
 * ## Regeln beim Uebersetzen
 *
 * **Die Platzhalter bleiben, die Wortstellung darf sich aendern.** `{{anzahl}}` steht
 * anderswo oft an anderer Stelle als im Deutschen; genau dafuer sind sie da. Ein
 * verlorener Platzhalter ist der teuerste Fehler in einem Katalog - die Auskunft, die er
 * tragen sollte, fehlt danach ersatzlos. `npm run sprachpruefung` faengt das ab.
 *
 * **Nicht laenger als das Deutsche.** Die Oberflaeche ist auf deutsche Wortlaengen
 * ausgelegt; wo eine Uebersetzung laenger wuerde, ist meistens eine kuerzere die bessere.
 *
 * ## Was am Russischen anders ist
 *
 * **Drei Mehrzahlformen nach der Endziffer.** 1, 21, 31 -> `one`; 2-4, 22-24 -> `few`;
 * alles uebrige samt der 0 -> `many`. Beim Wort "Nachricht" (письмо) sind alle drei
 * verschieden, und zwar deutlich: "1 новое письмо", "2 новых письма", "5 новых писем" -
 * Zahlwort, Eigenschaftswort und Hauptwort aendern sich zusammen. Auch das Zeitwort haengt
 * daran: "2 письма перемещены", aber "5 писем перемещено". `sprachpruefung` verlangt
 * deshalb bei jedem Mehrzahl-Schluessel alle drei Formen.
 *
 * **Wo `t()` statt `tp()` zaehlt, muss die Fuegung unbeugbar sein.** "alle {abstand} Tage"
 * gibt es nur EINMAL im Katalog, waere aber "каждые 2 дня" und "каждые 5 дней" - zwei
 * Formen. Deshalb steht dort die Ordnungszahl: "каждый {abstand}-й день". Die Endung "-й"
 * gilt fuer jede Zahl, die weibliche "-я" ebenso ("каждую {abstand}-ю неделю").
 *
 * **Anfuehrungszeichen: «Guillemets»** (U+00AB ... U+00BB), nicht die deutschen.
 *
 * **Die Werkzeugleiste traegt Ж, К, Ч** - so heissen die Knoepfe in jedem russischen
 * Textprogramm (жирный, курсив, подчёркнутый). Durchgestrichen heisst hier
 * "перечёркнутый" (П) und nicht das gelaeufigere "зачёркнутый", weil dessen З schon der
 * Ueberschrift gehoert (заголовок).
 *
 * **Kein Zeitwort in der Vergangenheit ueber den Nutzer.** Es traegt im Russischen das
 * Geschlecht: "ответил" (m.) gegen "ответила" (w.). Das Programm weiss es nicht, also
 * steht dort eine Fuegung ohne Vergangenheit - "От вас ещё нет ответа" statt "Sie haben
 * noch nicht geantwortet".
 */
