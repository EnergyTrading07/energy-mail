/**
 * Polnisch.
 *
 * Der Schluessel ist der deutsche Text - so steht er auch im Quelltext, und ein fehlender
 * Eintrag faellt auf Englisch und dann auf Deutsch zurueck, nie auf einen Bezeichner.
 * Was hier fehlt, findet `npm run sprachstand`.
 *
 * ## Regeln beim Uebersetzen
 *
 * **Die Platzhalter bleiben, die Wortstellung darf sich aendern.** `{{anzahl}}` steht
 * anderswo oft an anderer Stelle als im Deutschen; genau dafuer sind sie da. Ein
 * verlorener Platzhalter ist der teuerste Fehler in einem Katalog - die Auskunft, die er
 * tragen sollte, fehlt danach ersatzlos. `npm run sprachpruefung` faengt das ab.
 *
 * **Nicht laenger als das Deutsche.** Die Oberflaeche ist auf deutsche Wortlaengen
 * ausgelegt; wo eine Uebersetzung laenger wuerde, ist meistens eine kuerzere die bessere.
 *
 * ## Was am Polnischen anders ist
 *
 * **Drei Mehrzahlformen, und sie sind nicht kosmetisch.** 1 -> `one`, 2-4 -> `few`,
 * 5 und mehr sowie die 0 -> `many`; und das gilt je Endziffer, weshalb 22 wieder `few`
 * ist und 25 wieder `many`. Wo ein Zahlwort davorsteht, aendert sich mit der Form auch
 * das Wort danach: "1 nowa wiadomosc", "2 nowe wiadomosci", "5 nowych wiadomosci". Wer
 * mit zwei Formen auskaeme, schriebe in vier von fuenf Faellen falsch. `sprachpruefung`
 * verlangt deshalb bei jedem Mehrzahl-Schluessel alle drei.
 *
 * **Kein Wort an einen Platzhalter beugen.** Was in `{ordner}` oder `{was}` steht, ist ein
 * Name, den niemand kennt - er kann nicht dekliniert werden. Die Saetze hier stellen
 * solche Einsetzungen deshalb entweder in Anfuehrungszeichen ("Nie udalo sie: „{was}“")
 * oder haengen die Endung an ein festes Wort daneben ("do folderu „{ordner}“").
 *
 * **Anfuehrungszeichen: „polnisch“ unten und oben** (U+201E ... U+201D) - das untere
 * oeffnende ist dasselbe wie im Deutschen, das schliessende nicht.
 *
 * **Die Werkzeugleiste traegt B, I, U, S.** Sonst folgt die Aufschrift dem Wort der
 * Sprache (tuerkisch K fuer "kalin"); hier ginge das nicht: pogrubienie, podkreslenie und
 * przekreslenie fangen alle drei mit P an. B/I/U/S ist ohnehin, was polnisches Word und
 * jeder Web-Editor zeigen. Nur die Ueberschrift bekommt ihr eigenes N fuer "naglowek".
 */
